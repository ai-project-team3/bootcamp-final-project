/** 장면마다 "뒤에서 무슨 일이 일어나는가" — 근거 문서의 번호를 함께 적는다. */
fun behindText(scene: Scene): String = when (scene) {
    Scene.ADULT -> """
        • 어른과 아이가 함께 보는 첫 화면. 아래 마스코트 말풍선은 없다 (v0.8)
        • 위 왼쪽 [🧒 아이 | 👪 부모] — 부모를 누르면 비밀번호 4자리 → 부모 모드
        • 위 오른쪽 하루 별 — 별 아이콘 + 왼쪽 변이 열린 둥근 틀 안의 숫자. 한도를 끄면 ∞ [⭐2]
        • [이야기 만들기]를 누르면 별 하나를 쓴다. 0이면 한 번만 안내하고 막는다 [결정 2]
        • 부모 설정 "시작할 때 비밀번호"를 켜면 🔒 표시 → 비밀번호를 넣어야 시작 (별 소모 · 과몰입 방지)
        • [📚 책장] — 만든 책이 꽂혀 있다 (다시 읽기는 아직 없음)
    """.trimIndent()

    Scene.PARTNER -> """
        • "오늘은 누구랑 같이 이야기를 만들어?" — 그림 카드 없이 **녹음으로** 답한다 (9/17)
          Whisper 글자를 호칭 사전(엄마 · 아빠 · 이모 · 할머니 · 할아버지 · 친구)과 맞춘다 · 말한 뒤에만 그 사람 그림이 나타난다
        • 무응답이면 카드 대신 다른 말로 두 번 더 묻고("옆에 누가 있어?"), 그래도 없으면 "엄마"로 두고 진행
        • 고른 사람이 이후 모든 호칭이 된다: 질문("엄마, …엄마는 뭘 도와줄까?") · 먼저 말하는 갈래 · 책 표지 · 마지막 쪽 · 부모 기록
        • 할머니 · 할아버지는 높임말("할머니께서는 … 주셨어요"), 친구는 친구 말투("친구야, 너는 뭘 해 줄래?")
        • 함께 하는 사람의 말은 칸을 채우지 않고 수준 판단에도 쓰지 않는다 — 함께하기 기록 재료
    """.trimIndent()

    Scene.BESTIARY -> """
        • 주인공 4칸 · 빈 칸은 점선 ＋ [⭐8]
        • 주인공은 ＋ 버튼을 눌렀을 때 한 번만 만든다. 이야기 중에는 고정 [⭐20]
        • 확정된 주인공은 고정 스프라이트로 재사용, 다른 그림 나라에 가도 그대로 [⭐26 · 27]
    """.trimIndent()

    Scene.MAKEHERO -> """
        • 두 방식 — 골라서 만들기(토글 · 생성 없음) / 말로 만들기(질문 → 녹음 → 속성값 → ComfyUI)
        • 소크라틱 질문: "머리는 짧아, 길어?"처럼 선택지를 말하지 않고
          "우리 주인공은 머리가 어떻게 생겼을까?" · 말이 없으면 "거울 속 ○○ 머리를 떠올려 봐" (v0.8)
        • 확인은 카드 "좋아 / 싫어" [⭐21] · 수정 2번 → 다 쓰면 만든 3장 중 고르기 [결정 29]
        • 발화 원문이 아니라 속성값만 서버로 · 음성 사본 즉시 삭제 [조사3 §2-3]
    """.trimIndent()

    Scene.PLACE -> """
        • 기준 질문 1 (고정) "오늘은 어디로 가 볼까?" — 장소 이름을 먼저 말하지 않는다 [결정 30 · 14 · 25번 B안]
        • 무응답: 쉬운 질문 → 그때 카드 3장 → 교체 3번 → 마스코트 [⭐5 · ⭐22] · 이 장면에서는 [직접 그리기]를 쓰지 않는다
        • 프리셋에 없는 장소("눈 오는 데")면 배경 1장을 새로 만든다 [구현대본 §6]
        • 도착하면 함께 하는 사람이 한마디 → 질문 은행에서 "뭐가 있을까?" 변형 하나
        • 아이가 말한 것(별 · 행성 · 산호 · 구름 · 화산 …)은 **새 그림을 얹지 않고 배경 그림에 이미 그려진 그 자리**가
          반짝이며 통 튄다 (9/17) — 배경 1장마다 6~9곳을 좌표로 정해 둠. 누르면 그 부분이 통 튀고 "반짝!" 같은 글자
        • 이 턴의 답(길이 · 까닭 · 덧붙임)이 처음 수준 판단 재료 [역할1 조사2 §3]
    """.trimIndent()

    Scene.EVENT -> """
        • 사건은 장소마다 다르다 — 로켓 덜컹 · 소용돌이 · 땅 울림. 배경 속 것들도 같이 흔들린다
        • 기준 질문 2 (고정) "누가 흔들었을까?" — 그림 카드를 쓰지 않는다
        • 무응답: "창문 밖을 잘 봐. 뭐가 보여?" → "쉿, 창문에서 뭔가 움직였어!" → 마스코트가 "혹시 ○○일까?"
        • 함께 하는 사람만 말하면 2~3초 뒤 "○○는 어떻게 생각해?"를 한 번 [⭐5 · 구현대본 §0-2]
        • 이어 묻기는 질문 은행 — "그다음엔?" · "뭐라고 말했을까?" · "누가 제일 놀랐을까?" 중 수준에 맞는 것, 지난번에 안 쓴 것
        • 처음 두 턴의 신호로 수준을 다시 본다: 올림(S1 또는 S2) 2턴 연속 → 한 칸 위 / 짧은 답 · 카드 · 무응답 2턴 연속 → 한 칸 아래
    """.trimIndent()

    Scene.CAUSE -> """
        • 까닭 질문 (질문 은행 · 3변형) → 함께 하는 사람이 먼저 말함 → 2.5초 뒤 "○○는 어떻게 생각해?"
        • 답의 까닭 종류(심심 · 놀고 싶음 · 장난 · 힘자랑 · 길 잃음 · 배고픔 · 다침 …)가 템플릿 갈래를 정한다
        • 3턴째 템플릿 확정 [⭐4 · 13 · 역할1 조사2 표 #1]
          고르며 짓기 → E 여정형 6쪽 · 이어 짓기 → C 위험-대응-도움형 / D 방문자-직업수행형(길 잃음 · 배고픔 · 다침) 7쪽
          · 까닭 짓기 → A 도전-성취형 / G 우화-교훈형(장난 · 힘자랑) 8쪽
        • 속성 축(교훈 · 체험 · 상황 이해 · 직업 체험)은 까닭 종류로 붙는다 [결정 13]
        • 까닭 짓기일 때만 가정 질문 "네가 ○○였다면?" · "다른 방법은 없었을까?" [역할1 조사2 #5]
        • 마음 말하기 · 마음 카드는 수준 신호가 아니다
    """.trimIndent()

    Scene.DRAW -> """
        • "○○는 어떻게 생겼을까? 그려 줄래?" — 아이 그림은 원본 그대로 + 흰 오려낸 테두리 [27]
        • 다 그리면 그림판을 접고 그린 그림만 보여 준다
        • 이름도 마스코트가 묻는다: "○○한테 어울리는 이름은 뭘까?" · 무응답이면 "○○ 친구"
        • 이름은 이름 사전에 넣고, LLM에는 {친구1}로만 [조사3 §3-2] · 입 위치는 한 점만 저장
    """.trimIndent()

    Scene.PLOT -> """
        • 템플릿이 정한 이야기 칸 2개를 질문 은행에서 묻는다 (매번 다른 변형 · 더미 답 5~7개씩)
          E: 어디를 지나갈까 · 거기서 뭘 봤어 / C: 뭐라고 말할까 · 누구에게 도움을 청할까
          D: 뭐가 필요할까 · 누가 되어 도와줄까 / A: 처음엔 어떻게 해 봤을까 · 왜 잘 안 됐을까
          G: 계속 흔들다 어떻게 됐을까 · 무엇을 알게 됐을까
        • 답이 그대로 책의 해당 쪽 문장이 된다 → 같은 템플릿이라도 책이 매번 다르다
        • 이야기 턴 4 · 5 — 여기서도 수준이 움직일 수 있지만 템플릿은 그대로, 질문 난이도와 다음 세션 시작점만 바뀐다
    """.trimIndent()

    Scene.DINO -> """
        • 아이가 먼저 "공룡도 데려갈래!" → 그 말에서 되묻는다: "공룡? 어떤 공룡이야? 어떻게 생겼어?"
        • 뜻이 여럿인 말이라 확인 카드 3장(티라노 · 긴목공룡 · 뿔공룡) — 카드가 먼저 나오는 유일한 자리 [구현대본 §0-1]
        • 생김새 낱말("뿔이 세 개")을 선택지와 맞춘다 [조사3 §3-1]
    """.trimIndent()

    Scene.SOUND -> """
        • "○○는 어떤 소리를 낼까?" → 🎤 녹음 · [다시] 2번 [초안 장면 8]
        • 원본 녹음 그대로 책에 붙는다 · 폰 밖으로 나가지 않는다 [조사3]
    """.trimIndent()

    Scene.CHECK -> """
        • 확인 카드 좋아 / 싫어 / 직접 그리기 · 위 오른쪽 "다시 그리기 n/2" [⭐21 · 24]
        • 싫어 → "어디를 바꾸면 더 좋을까?" (열린 질문)
        • 색 · 크기 · 표정은 다시 생성하지 않는다 [⭐26] · 모양 · 종류만 재생성 2회 → 다 쓰면 3장 중 고르기
        • 서랍 [그림 생성 느리게] → 8초 안내 · 15초 취소 [역할3]
    """.trimIndent()

    Scene.SOLUTION -> """
        • 해결 질문(질문 은행) → 고른 방법이 마지막 쪽 문장 + 미션 2에서 건넬 물건이 된다
        • 템플릿 마무리 질문: E "마지막엔 어디에 도착할까?" · A/G "오늘 무엇을 알게 됐을까?"(까닭 짓기만)
        • 마음 질문 "그러면 ○○ 기분은 어떨까?" — 기록 재료 (신호 아님)
        • 함께 하는 사람 참여 — 누구냐에 따라 질문 · 답이 다르다 (엄마 · 아빠 · 이모 / 할머니 · 할아버지 높임 / 친구)
          → 답하면 마지막 쪽에 한 줄 · 답하지 않으면 대신 고르지 않고 책에도 넣지 않는다
        • 필수 칸 6개가 다 차면 진행 막대가 가득 차고 끝의 별이 켜진다 → 동화책 시작 [⭐9]
    """.trimIndent()

    Scene.MAKING -> """
        • 템플릿(6~8쪽) + 모은 이야기 조각 → 쪽마다 자막 · 제목 (실제 앱: 이름을 가려 Anthropic → JSON → 폰에서 이름 복원)
        • 제목은 묻지 않는다 — 템플릿과 대화로 지어 준다. 책장에서 바꿀 수 있게 할 자리
        • 확정된 그림만 다시 쓴다 [⭐26]
    """.trimIndent()

    Scene.BOOK -> """
        • 책은 전체 화면 · 쪽 수는 템플릿대로 6 · 7 · 8쪽 (9/17) · 위 오른쪽 점과 "n/전체"
        • 쪽마다 그림 구성이 다르다 — 출발 · 흔들림 · 대화 · 여정 · 실패 · 미션 · 함께
        • 배경 속 것들도 누르면 반응한다 (돋보기면 이름)
        • 도구 4종(손 · 뿅망치 · 깃털 · 돋보기) — 누른 것 바로 위에 글자. 네모 물결은 없다
        • 미션 1 = 장면 4의 "누가 흔들었나"에서 나온 흔적을 문질러 치우기 / 미션 2 = 장면 10에서 말한 것을 친구에게 건네기
        • 미션은 2개 [⭐7] · 첫 미션은 늘 쉬운 것부터 · 도움 받으면 다음은 탭 [역할1 §7] · 시간 · 시도 횟수 저장 안 함 [16]
    """.trimIndent()

    Scene.FRIENDS -> """
        • 오늘 만난 친구마다 [또 만날래 💛] [안녕 👋] — 지우는 선택지는 없다 [구현대본 S10]
        • "또 만날래"로 고른 친구만 다음 이야기의 확인 카드 후보 [⭐26]
    """.trimIndent()

    Scene.END -> """
        • 선물이 차례로 하나씩 [조사3 §1-2] → "책 다 만들었다! 고생했어~~" → [책장에 꽂기]
        • 선물 2개: 해결 방법 도감 한 칸 [⭐9] + 무지개 크레용
    """.trimIndent()

    Scene.SHELF -> """
        • 방금 만든 책이 위에서 내려와 책장에 꽂힌다 · "새 책!" · ✏️ 이름 바꾸기 자리 (v0.8)
        • 다시 읽기는 아직 없다 — 책을 누르면 흔들리기만
        • [🏠 처음으로] — 이야기만 지우고 책장 · 부모 설정 · 하루 별은 그대로 · 다음 책을 권하지 않는다 [⭐2]
    """.trimIndent()

    Scene.PARENT -> """
        • 비밀번호 4자리로 들어간다. 아래 마스코트 · 버튼은 없다
        • 오늘의 기록 — 6축 카드 · 말한 방식 원그래프 · 본인 대비 · 누리과정 · 질문 카드 · 고지.
          등급 · 나이 비교 · 수준 이름은 보여주지 않는다 [16]
        • 설정 — 하루 한도(토글 + 권수) · 이야기 시작 비밀번호(토글) · 그림체 4종 · 데이터.
          다시 그리기 상한은 설정에서 뺐다 (v0.8)
        • [🏠 아이 모드로] → 첫 화면
    """.trimIndent()
}

