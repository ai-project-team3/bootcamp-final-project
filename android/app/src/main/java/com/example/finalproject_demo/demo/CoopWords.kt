/** 어절 첫머리로 거친 말이 있나 */
fun hasRoughWord(text: String): Boolean =
    text.split(Regex("[\\s,.!?~]+")).any { w -> COOP_ROUGH_WORDS.any { w.startsWith(it) } }

/** 상상 낱말이 있나 (어절 첫머리. 한 글자 낱말 「용」은 조사만 붙은 꼴일 때만 — 「용기」는 아니다) */
fun hasFantasyWord(text: String): Boolean =
    text.split(Regex("[\\s,.!?~]+")).any { w ->
        COOP_FANTASY_WORDS.any { f ->
            if (f.length == 1) Regex("^$f(이|가|은|는|을|를|이랑|랑|도|아|야)?$").matches(w) else w.startsWith(f)
        }
    }
